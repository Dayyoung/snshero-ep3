export function localizeCardText(textEn: string, lang: HeroLanguage): string {
  if (!textEn || lang === 'en' || lang === 'ko') return textEn;
  const rules = CARD_TEXT_REPLACEMENTS[lang];
  if (!rules) return textEn;
  let result = textEn;
  for (const [regex, replacement] of rules) {
    result = result.replace(regex, replacement);
  }
  return result;
}
